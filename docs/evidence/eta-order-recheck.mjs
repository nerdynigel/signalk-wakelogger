import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
const source = readFileSync(resolve(process.argv[2], 'frontend/app/lib/racePlanTiming.js'), 'utf8');
const { racePlanLegTimings } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const planned_start_time = '2026-10-11T12:00:00Z';
const normal = { distance_nm: 1, estimated_sog_knots: 5 };
const first = { ...normal, estimated_start_time: planned_start_time, estimated_finish_time: '2026-10-15T16:00:00Z' };
const run = legs => racePlanLegTimings({ planned_start_time, legs });
const derived = run([first, normal]);
assert.equal(derived[1].start, '2026-10-15T16:00:00.000Z');
assert.equal(derived[1].finish, '2026-10-15T16:12:00.000Z');
const overlap = run([first, { ...normal, estimated_start_time: '2026-10-12T12:00:00Z', estimated_finish_time: '2026-10-16T12:00:00Z' }, normal]);
assert.deepEqual(overlap.slice(1), [{ start: null, finish: null }, { start: null, finish: null }]);
const recovery = run([first, { ...normal, estimated_sog_knots: 0 }, normal, { ...normal, estimated_start_time: '2026-10-16T12:00:00Z' }, normal]);
assert.equal(recovery[2].start, null);
assert.equal(recovery[3].start, '2026-10-16T12:00:00.000Z');
assert.equal(recovery[4].start, recovery[3].finish);
console.log(JSON.stringify({ result: 'PASS', sha256: createHash('sha256').update(source).digest('hex'), derived, overlap, recovery }, null, 2));
